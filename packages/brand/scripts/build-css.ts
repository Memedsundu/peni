/**
 * Writes apps/web/src/app/tokens.css from src/tokens.ts, in exactly the §3.5 structure:
 * the light :root block, the dark block emitted twice (system preference unless forced light,
 * and forced dark), and the forced-light color-scheme.
 *
 *   pnpm brand:css            write the file
 *   pnpm brand:css --check    exit 1 if the file on disk differs (CI)
 *
 * Runs with `node --experimental-strip-types`, so it imports only tokens.ts (which has no
 * imports of its own) and uses explicit `.ts` specifiers.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { cafeHueOrder, cafeHues, cssVarName, dark, light, plateText, plateText2, webEffects } from "../src/tokens.ts";
import type { TokenName, Tokens, WebEffects } from "../src/tokens.ts";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "../../..");
export const OUT = resolve(repo, "apps/web/src/app/tokens.css");

/** One line per group, as in §3.5. The press group is light-only (it never changes). */
const GROUPS: TokenName[][] = [
  ["bg", "surface", "surface2"],
  ["ink", "ink2", "line", "lineStrong"],
  ["primary", "onPrimary", "primaryPressed"],
  ["peni", "onPeni", "peniInk", "peniSoft"],
  ["aski", "onAski", "askiPressed", "askiInk", "askiSoft", "hook"],
  ["masa", "onMasa", "masaInk", "masaSoft"],
  ["success", "onSuccess", "onSuccess2", "successInk", "successSoft"],
  ["danger", "dangerSoft"],
  ["warning", "warningInk", "warningSoft"],
  ["focus"],
];
const PRESS: TokenName[] = ["press", "onPress", "onPress2"];

function tokenLine(t: Tokens, names: TokenName[]): string {
  return names.map((n) => `--${cssVarName(n)}:${t[n]};`).join(" ");
}

function effectLines(e: WebEffects): string[] {
  return [
    `--plate-ring: ${e.plateRing};`,
    `--elev-1: ${e.elev1};`,
    `--elev-2: ${e.elev2};`,
    `--fis-shadow: ${e.fisShadow};`,
    `--grain: ${e.grain};`,
  ];
}

function indent(lines: string[], depth: number): string {
  const pad = "  ".repeat(depth);
  return lines.map((l) => pad + l).join("\n");
}

function verifyGroupsCoverEveryToken() {
  const grouped = new Set([...GROUPS.flat(), ...PRESS]);
  const missing = (Object.keys(light) as TokenName[]).filter((n) => !grouped.has(n));
  if (missing.length) throw new Error(`build-css: tokens missing from GROUPS: ${missing.join(", ")}`);
  const pressDiffers = PRESS.filter((n) => light[n] !== dark[n]);
  if (pressDiffers.length) throw new Error(`build-css: press tokens must match in both themes: ${pressDiffers.join(", ")}`);
}

export function buildCss(): string {
  verifyGroupsCoverEveryToken();

  const lightBlock = [
    "color-scheme: light;",
    ...GROUPS.map((g) => tokenLine(light, g)),
    tokenLine(light, PRESS),
    `--plate-text:${plateText}; --plate-text-2:${plateText2};`,
    cafeHueOrder.map((h) => `--hue-${h}:${cafeHues[h]};`).join(" "),
    ...effectLines(webEffects.light),
  ];
  const darkBlock = ["color-scheme: dark;", ...GROUPS.map((g) => tokenLine(dark, g)), ...effectLines(webEffects.dark)];

  return [
    "/* Generated by packages/brand/scripts/build-css.ts from packages/brand/src/tokens.ts.",
    "   Do not edit by hand: change tokens.ts, then run `pnpm brand:css` (CI runs `pnpm brand:css --check`). */",
    ":root {",
    indent(lightBlock, 1),
    "}",
    "/* DARK — the same block is emitted twice */",
    "@media (prefers-color-scheme: dark) {",
    '  :root:not([data-theme="light"]) {',
    indent(darkBlock, 2),
    "  }",
    "}",
    ':root[data-theme="dark"] {',
    indent(darkBlock, 1),
    "}",
    ':root[data-theme="light"] { color-scheme: light; }',
    "",
  ].join("\n");
}

function main() {
  const css = buildCss();
  const rel = relative(process.cwd(), OUT) || OUT;
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(OUT, "utf8");
    } catch {
      console.error(`brand:css --check: ${rel} does not exist. Run \`pnpm brand:css\`.`);
      process.exit(1);
    }
    if (current !== css) {
      console.error(`brand:css --check: ${rel} has drifted from packages/brand/src/tokens.ts. Run \`pnpm brand:css\`.`);
      process.exit(1);
    }
    console.log(`brand:css --check: ${rel} is up to date.`);
    return;
  }
  writeFileSync(OUT, css);
  console.log(`brand:css: wrote ${rel}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
